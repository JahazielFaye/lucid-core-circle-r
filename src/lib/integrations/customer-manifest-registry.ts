import 'server-only';

import { createClient } from '@/utils/supabase/server';
import { customerManifestSchema, type CustomerReviewManifest } from '@/lib/integrations/customer-review-manifest-contract';

export class CustomerManifestRegistryAuthError extends Error {}

type Decision = 'APPROVE' | 'REJECT' | 'NEEDS_REVIEW';

async function context() {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) throw new CustomerManifestRegistryAuthError('An authenticated Lucid Core session is required.');
  const { data: profile, error } = await supabase.from('profiles').select('id, organization_id, active, role').eq('id', user.id).maybeSingle();
  if (error || !profile?.active) throw new CustomerManifestRegistryAuthError('An active Lucid Core profile is required.');
  return { supabase, profile };
}

export async function registerCustomerReviewManifest(rawManifest: unknown) {
  const manifest = customerManifestSchema.parse(rawManifest);
  const { supabase, profile } = await context();
  if (profile.role !== 'lucid_admin') throw new CustomerManifestRegistryAuthError('Only Lucid Admin can register a Customer review manifest.');
  if (manifest.organization_id !== profile.organization_id || manifest.generated_by.actor_id !== profile.id) {
    throw new CustomerManifestRegistryAuthError('This review manifest was not generated by your active organization session.');
  }
  const { data, error } = await supabase.rpc('register_customer_review_manifest', { p_manifest: manifest });
  if (error) throw new Error(error.message);
  return data as { registry_id: string; manifest_id: string; manifest_version: number; status: string; registered: boolean };
}

export async function readCustomerReviewManifestRegistry(registryId: string) {
  const { supabase, profile } = await context();
  const { data: manifest, error: manifestError } = await supabase
    .from('customer_review_manifests')
    .select('id,manifest_id,manifest_version,source_hash,plan_hash,status,generated_at,generated_by,environment,counts,canonical_manifest,registered_at')
    .eq('id', registryId).eq('organization_id', profile.organization_id).maybeSingle();
  if (manifestError) throw new Error(manifestError.message);
  if (!manifest) throw new Error('Review manifest is unavailable for your organization.');
  const { data: approvals, error: approvalError } = await supabase
    .from('customer_review_manifest_approvals')
    .select('id,reviewer_id,reviewer_role,decision,comment,source_hash,plan_hash,decided_at')
    .eq('manifest_registry_id', registryId).eq('organization_id', profile.organization_id).order('decided_at', { ascending: false });
  if (approvalError) throw new Error(approvalError.message);
  const { data: invalidation, error: invalidationError } = await supabase
    .from('audit_events')
    .select('actor_id,details,created_at')
    .eq('organization_id', profile.organization_id)
    .eq('entity_type', 'customer_review_manifest')
    .eq('entity_id', registryId)
    .eq('action', 'customer review manifest invalidated')
    .order('created_at', { ascending: false })
    .limit(1)
    .maybeSingle();
  if (invalidationError) throw new Error(invalidationError.message);
  return {
    manifest,
    approvals: approvals || [],
    viewerRole: profile.role,
    invalidation: invalidation ? {
      reason: typeof invalidation.details?.reason === 'string' ? invalidation.details.reason : null,
      invalidatedAt: invalidation.created_at,
      invalidatedBy: invalidation.actor_id,
    } : null,
  };
}

export async function recordCustomerReviewManifestDecision(input: { registryId: string; manifestId: string; manifestVersion: number; sourceHash: string; planHash: string; decision: Decision; comment?: string }) {
  const { supabase, profile } = await context();
  if (!['APPROVE', 'REJECT', 'NEEDS_REVIEW'].includes(input.decision)) throw new Error('Unsupported review decision.');
  const { data, error } = await supabase.rpc('record_customer_review_manifest_decision', {
    p_registry_id: input.registryId,
    p_manifest_id: input.manifestId,
    p_manifest_version: input.manifestVersion,
    p_source_hash: input.sourceHash,
    p_plan_hash: input.planHash,
    p_decision: input.decision,
    p_comment: input.comment?.trim() || null,
  });
  if (error) throw new Error(error.message);
  return { ...(data as { approval_id: string; status: string; decision: Decision; commit_eligible: boolean }), viewerRole: profile.role };
}

export async function invalidateCustomerReviewManifest(input: { registryId: string; reason: string }) {
  const reason = input.reason.trim();
  if (!reason) throw new Error('An invalidation reason is required.');
  const { supabase, profile } = await context();
  if (profile.role !== 'lucid_admin') throw new CustomerManifestRegistryAuthError('Only Lucid Admin can invalidate a Customer review manifest.');
  const { data, error } = await supabase.rpc('invalidate_customer_review_manifest', {
    p_registry_id: input.registryId,
    p_reason: reason,
  });
  if (error) throw new Error(error.message);
  return data as { registry_id: string; status: 'INVALIDATED' };
}
